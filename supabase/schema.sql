-- This function is private: closure calls it inside the same transaction.
create or replace function club_private.capture_awards(p_season integer) returns void
language plpgsql security definer set search_path='' as $$
declare v_awards jsonb; v_award text; v_winners jsonb;
begin
 if exists(select 1 from club_private.season_awards where season=p_season) then return; end if;
  with totals as (
   select p.id,p.name,coalesce(sum((r.value->>'goals')::int),0) goals,
    coalesce(sum((r.value->>'own')::int),0) own,
    count(*) filter(where (r.value->>'present')::boolean) apps
   from club_private.players p left join club_private.matches m on m.season=p_season and m.cancelled_at is null and m.result ? p.id::text
   left join lateral jsonb_each(m.result) r on r.key=p.id::text group by p.id,p.name
  ), scores as (
   select t.id,t.name,v.metric,v.total from totals t cross join lateral (values ('goals',t.goals),('own',t.own),('apps',t.apps)) v(metric,total)
  ), ranked as (
   select *,max(total) over(partition by metric) maximum from scores
  ), winners as (
   select metric,jsonb_agg(jsonb_build_object('id',id,'name',name) order by id) identities from ranked where total=maximum and maximum>0 group by metric
  ) select coalesce(jsonb_object_agg(metric,identities),'{}'::jsonb) into v_awards from winners;
 v_awards:=jsonb_build_object('goals','[]'::jsonb,'own','[]'::jsonb,'apps','[]'::jsonb)||v_awards;
 foreach v_award in array array['pollone','bidone'] loop
  with latest as (
   select id,status from club_private.rounds where season=p_season and award=v_award order by turn desc limit 1
  ), counts as (
   select p.id,p.name,count(*) votes from latest r join club_private.ballots b on b.round_id=r.id
   join club_private.players p on p.id=b.candidate_id where r.status='final' group by p.id,p.name
  ) select coalesce(jsonb_agg(jsonb_build_object('id',id,'name',name) order by id),'[]'::jsonb)
   into v_winners from counts where votes=(select max(votes) from counts);
  v_awards:=v_awards||jsonb_build_object(v_award,v_winners);
 end loop;
 insert into club_private.season_awards(season,awards) values(p_season,v_awards) on conflict(season) do nothing;
end $$;
revoke all on function club_private.capture_awards(integer) from public,anon,authenticated;

