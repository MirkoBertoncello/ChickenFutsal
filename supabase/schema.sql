-- RPC di servizio: solo l'Edge Function può ottenere gli indirizzi push.
create function public.club_claim_push(p_limit integer default 20) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_jobs jsonb;
begin
 perform club_private.enqueue_reminders();
 with chosen as (
  select q.id from club_private.push_queue q
  where q.attempts<3 and (q.status='pending' or (q.status in ('processing','failed') and q.claimed_at<now()-interval '10 minutes'))
  order by q.id limit least(greatest(p_limit,1),20) for update skip locked
 ), claimed as (
  update club_private.push_queue q set status='processing',attempts=attempts+1,claim_token=gen_random_uuid(),claimed_at=now()
  from chosen c where q.id=c.id returning q.*
 )
 select coalesce(jsonb_agg(jsonb_build_object('id',q.id,'claim',q.claim_token,'body',n.text,
 'subscriptions',(select coalesce(jsonb_agg(s.subscription),'[]'::jsonb) from club_private.push_subscriptions s where s.player_id=q.player_id))),'[]'::jsonb)
 into v_jobs from claimed q join club_private.notifications n on n.id=q.notification_id;
 return v_jobs;
end $$;
revoke all on function public.club_claim_push(integer) from public,anon,authenticated;
grant execute on function public.club_claim_push(integer) to service_role;

