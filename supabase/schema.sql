-- ChickenFutsal: un gruppo privato, stagioni e turni indipendenti per premio.
-- Eseguire una volta nel SQL Editor Supabase. Nessuna tabella è leggibile dal client.
create schema if not exists club_private;
revoke all on schema club_private from public, anon, authenticated;
create table club_private.players (
 id bigint generated by default as identity primary key,
 name text not null check(length(name) between 1 and 60),
 role text not null default 'Regista',
 occasional boolean not null default false,
 active boolean not null default true,
 ratings jsonb not null default '[60,60,60,60,60,60]'::jsonb
);
create table club_private.members (
 player_id bigint primary key references club_private.players(id),
 email text unique not null check(email=lower(email)),
 is_admin boolean not null default false,
 see_all boolean not null default false
);
create table club_private.matches (
 id bigint generated always as identity primary key,
 season integer not null,
 match_date date not null,
 match_time time not null,
 field text not null check(length(field) between 1 and 100),
 team_a jsonb not null, team_b jsonb not null,
 cancelled_at timestamptz, cancellation_reason text check(length(cancellation_reason)<=200),
 result jsonb, updated_at timestamptz not null default now()
);
create table club_private.rounds (
 id bigint generated always as identity primary key,
 season integer not null,
 award text not null check(award in ('pollone','bidone')),
 turn integer not null check(turn between 1 and 4),
 candidates jsonb not null,
 status text not null default 'open' check(status in ('open','closed','final')),
 unique(season,award,turn)
);
create table if not exists club_private.seasons (
 id integer primary key, name text not null check(length(name) between 1 and 60),
 started_on date not null, closed_at timestamptz
);
create unique index if not exists one_active_season on club_private.seasons ((true)) where closed_at is null;
insert into club_private.seasons(id,name,started_on,closed_at)
select y,case when y=2026 then '2025/2026' else y::text end,make_date(y,1,1),case when y=max(y) over() then null else now() end
from (select season y from club_private.matches union select season from club_private.rounds union select 2026) t
on conflict(id) do nothing;
alter table club_private.seasons enable row level security;

