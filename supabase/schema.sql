-- Called by the existing service-only push queue RPC every time the sender runs.
create or replace function club_private.enqueue_reminders(p_now timestamptz default now()) returns integer
language plpgsql security definer set search_path='' as $$
declare
 cfg club_private.reminder_settings%rowtype; m club_private.matches%rowtype;
 kickoff timestamptz; due timestamptz; result_due timestamptz; offset_hours numeric;
 offsets numeric[]; pid bigint; note bigint; key text; reminder_number integer; added integer:=0;
begin
 perform pg_advisory_xact_lock(712026);
 select * into cfg from club_private.reminder_settings where singleton;
 if not found then return 0; end if;
 -- Suppress stale queued reminders before sending, including cancelled games, completed
 -- scores, removed participants/admins, disabled reminders and past kickoffs.
 update club_private.push_queue q set status='sent',claim_token=null
 from club_private.notifications n join club_private.matches mm on mm.id=n.match_id
 where q.notification_id=n.id and n.reminder_key is not null and q.status<>'sent' and (
  mm.cancelled_at is not null or mm.result is not null or
  not exists(select 1 from club_private.seasons where id=mm.season and closed_at is null) or
  (n.reminder_key like 'participant:%' and (
   not cfg.participant_enabled or
   not(mm.team_a @> jsonb_build_array(n.player_id) or mm.team_b @> jsonb_build_array(n.player_id)) or
   p_now>=(mm.match_date+mm.match_time) at time zone 'Europe/Rome' or
   not (
    (cfg.first_enabled and n.reminder_key='participant:'||extract(epoch from ((mm.match_date+mm.match_time) at time zone 'Europe/Rome')-cfg.first_hours*interval '1 hour')::bigint::text) or
    (cfg.second_enabled and n.reminder_key='participant:'||extract(epoch from ((mm.match_date+mm.match_time) at time zone 'Europe/Rome')-cfg.second_hours*interval '1 hour')::bigint::text)
   ) or
   (cfg.second_enabled and p_now>=((mm.match_date+mm.match_time) at time zone 'Europe/Rome')-cfg.second_hours*interval '1 hour' and
    n.reminder_key<>'participant:'||extract(epoch from ((mm.match_date+mm.match_time) at time zone 'Europe/Rome')-cfg.second_hours*interval '1 hour')::bigint::text)
  )) or
  (n.reminder_key like 'result:%' and (not cfg.result_enabled or not exists(select 1 from club_private.members where player_id=n.player_id and is_admin) or
   not exists(select 1 from generate_series(0,case when cfg.result_repeat_enabled then cfg.result_max_reminders-1 else 0 end) i where
    n.reminder_key='result:'||extract(epoch from ((mm.match_date+mm.match_time) at time zone 'Europe/Rome')+cfg.match_duration_minutes*interval '1 minute'+cfg.result_delay_hours*interval '1 hour'+i*cfg.result_repeat_hours*interval '1 hour')::bigint::text)))
 );
 for m in select mm.* from club_private.matches mm join club_private.seasons s on s.id=mm.season
  where s.closed_at is null and mm.cancelled_at is null and mm.result is null loop
  kickoff:=(m.match_date+m.match_time) at time zone 'Europe/Rome';
  if cfg.participant_enabled and p_now<kickoff then
   offsets:=array[]::numeric[];
   if cfg.first_enabled then offsets:=array_append(offsets,cfg.first_hours); end if;
   if cfg.second_enabled then offsets:=array_append(offsets,cfg.second_hours); end if;
   -- Recover only the latest due reminder, never send both at once after an outage.
   select min(h) into offset_hours from unnest(offsets) h where p_now>=kickoff-h*interval '1 hour';
   if offset_hours is not null then
    due:=kickoff-offset_hours*interval '1 hour';key:='participant:'||extract(epoch from due)::bigint::text;
    -- A match created/rescheduled after this deadline already sent its own update notice.
    if m.updated_at<=due then
     for pid in select members.player_id from club_private.members members join club_private.players p on p.id=members.player_id and p.active where m.team_a @> jsonb_build_array(members.player_id) or m.team_b @> jsonb_build_array(members.player_id) loop
      note:=null;
      insert into club_private.notifications(player_id,match_id,text,reminder_key)
       values(pid,m.id,'Promemoria partita: '||m.match_date::text||' alle '||to_char(m.match_time,'HH24:MI')||' · '||m.field,key)
       on conflict(match_id,player_id,reminder_key) where reminder_key is not null do nothing returning id into note;
      if note is not null then insert into club_private.push_queue(player_id,notification_id) values(pid,note);added:=added+1;end if;
     end loop;
    end if;
   end if;
  end if;
  if cfg.result_enabled then
   result_due:=kickoff+cfg.match_duration_minutes*interval '1 minute'+cfg.result_delay_hours*interval '1 hour';
   if p_now>=result_due then
    reminder_number:=0;
    if cfg.result_repeat_enabled then reminder_number:=least(cfg.result_max_reminders-1,floor(extract(epoch from (p_now-result_due))/(cfg.result_repeat_hours*3600))::integer); end if;
    due:=result_due+reminder_number*cfg.result_repeat_hours*interval '1 hour';
    key:='result:'||extract(epoch from due)::bigint::text;
    for pid in select members.player_id from club_private.members members join club_private.players p on p.id=members.player_id and p.active where members.is_admin loop
     note:=null;
     insert into club_private.notifications(player_id,match_id,text,reminder_key)
      values(pid,m.id,'Risultato da registrare: partita del '||m.match_date::text||' alle '||to_char(m.match_time,'HH24:MI')||' · '||m.field,key)
      on conflict(match_id,player_id,reminder_key) where reminder_key is not null do nothing returning id into note;
     if note is not null then insert into club_private.push_queue(player_id,notification_id) values(pid,note);added:=added+1;end if;
    end loop;
   end if;
  end if;
 end loop;
 return added;
end $$;
revoke all on function club_private.enqueue_reminders(timestamptz) from public,anon,authenticated,service_role;

