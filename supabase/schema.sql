create function club_private.actor() returns bigint language plpgsql stable security definer set search_path='' as $$
declare v_id bigint;
begin
 if auth.uid() is null then raise exception 'Accedi al gruppo'; end if;
 select m.player_id into v_id from club_private.members m
 join auth.users u on lower(u.email)=m.email
 join club_private.players p on p.id=m.player_id and p.active
 where u.id=auth.uid() and u.email_confirmed_at is not null;
 if v_id is null then raise exception 'Account non invitato o email non confermata'; end if;
 return v_id;
end $$;
revoke all on function club_private.actor() from public;

